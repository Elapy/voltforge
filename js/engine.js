  /* ------------------------------------------------ CAD export (.scad)
     A parametric enclosure in real OpenSCAD source. Dimensions come from
     the actual parts in the project: the shared board + breadboard below,
     plus each block's cad() spec, which names the same real parts as its
     BOM and wiring (HC-SR501, HC-SR04, SG90, DHT module, soil probe...).
     The layout is computed here in JS and emitted as a variable block at
     the top of the file, so the user can adjust any dimension and
     re-render. No dimension is decorative — every hole, window, slot and
     bracket is positioned from a part's size and placement. */

  var CAD_COMMON = [
    { key: 'uno', name: 'Arduino Uno R3', w: 68.6, d: 53.4, h: 15, mount: 'floor' },
    { key: 'bb', name: 'Solderless breadboard, 400-point', w: 82, d: 55, h: 9, mount: 'floor' }
  ];

  function n1(v) { return Math.round(v * 10) / 10; }

  function cadLayout(block, p) {
    var spec = block.cad(p);
    var parts = CAD_COMMON.concat(spec.parts);
    var byMount = { floor: [], lid: [], front: [], top: [], horn: [], slot: [] };
    parts.forEach(function (part) { byMount[part.mount].push(part); });
    var floorRow = byMount.floor.concat(byMount.front); // front parts stand on the floor, against the front wall
    var x = 6, i, part;
    for (i = 0; i < floorRow.length; i++) { part = floorRow[i]; part.cx = x + part.w / 2; x += part.w + 6; }
    var floorW = x; // last part's right edge + end margin (x already includes a trailing 6 gap)
    var lx = 6;
    for (i = 0; i < byMount.lid.length; i++) { part = byMount.lid[i]; part.cx = lx + part.w / 2; lx += part.w + 8; }
    var lidW = byMount.lid.length ? lx - 2 : 0;
    var innerW = Math.max(floorW, lidW, 60);
    var depthParts = floorRow.concat(byMount.lid);
    var innerD = 10 + Math.max.apply(null, depthParts.map(function (q) { return q.d; }));
    var floorH = Math.max.apply(null, floorRow.map(function (q) { return q.h; }));
    var hangH = byMount.lid.length ? Math.max.apply(null, byMount.lid.map(function (q) { return q.h; })) : 0;
    var innerH = Math.max(34, floorH + hangH + 12);
    return { spec: spec, parts: parts, byMount: byMount, wall: 2.4, innerW: innerW, innerD: innerD, innerH: innerH };
  }

  function buildScadFile(project) {
    var block = blockById(project.blockId);
    var p = project.params;
    var L = cadLayout(block, p);
    var wall = L.wall;
    var out = [];
    var paramEcho = block.params.map(function (def) {
      var v = p[def.key];
      var shown = def.type === 'pin' ? 'D' + v : String(v);
      return ' *   ' + def.key + ' = ' + shown;
    }).join('\n');

    out.push('// ============================================================');
    out.push('// ' + project.name + ' — parametric enclosure (OpenSCAD)');
    out.push('// Generated by ' + SITE_NAME + ' (' + SITE_URL + ') — ' + TAGLINE);
    out.push('// Block: ' + block.name + ' · Board: Arduino Uno R3');
    out.push('// Your settings (the same values the sketch was built with):');
    out.push(paramEcho.replace(/^ \* /gm, '// '));
    out.push('// All dimensions are millimetres, taken from the real parts');
    out.push('// in this project\'s parts list. Supplier revisions vary a');
    out.push('// few mm — measure your parts and adjust the variables');
    out.push('// below before printing. Open in OpenSCAD, F6 to render,');
    out.push('// then File > Export > STL.');
    out.push('// ============================================================');
    out.push('');
    out.push('// ---------- part dimensions (mm) ----------');
    L.parts.forEach(function (part) {
      out.push(part.key + '_w = ' + n1(part.w) + ';  // ' + part.name);
      out.push(part.key + '_d = ' + n1(part.d) + ';');
      out.push(part.key + '_h = ' + n1(part.h) + ';');
      if (part.holeD) out.push(part.key + '_hole_d = ' + n1(part.holeD) + ';');
      if (part.holeGap) out.push(part.key + '_hole_gap = ' + n1(part.holeGap) + ';');
      if (part.holes) out.push(part.key + '_holes = ' + part.holes + ';');
      if (part.ventD) out.push(part.key + '_vent_d = ' + n1(part.ventD) + ';');
      if (part.slotW) out.push(part.key + '_slot_w = ' + n1(part.slotW) + ';');
      if (part.slotH) out.push(part.key + '_slot_h = ' + n1(part.slotH) + ';');
      if (part.cx !== undefined) out.push(part.key + '_cx = ' + n1(wall + part.cx) + ';  // centre of the part, from the box\'s left outer edge');
      if (part.note) out.push('//   ' + part.name + ': ' + part.note);
    });
    out.push('');
    out.push('// ---------- enclosure ----------');
    out.push('wall = ' + wall + ';');
    out.push('inner_w = ' + n1(L.innerW) + ';  // laid out from the parts above');
    out.push('inner_d = ' + n1(L.innerD) + ';');
    out.push('inner_h = ' + n1(L.innerH) + ';');
    out.push('outer_w = inner_w + 2 * wall;');
    out.push('outer_d = inner_d + 2 * wall;');
    out.push('lid_t = 2.4;');
    out.push('explode = 24;  // lid lift for preview — set to 0 for the closed box');
    out.push('$fn = 48;');
    out.push('');

    /* shell */
    out.push('module shell() {');
    out.push('  difference() {');
    out.push('    union() {');
    out.push('      cube([outer_w, outer_d, wall + inner_h]);');
    out.push('      // corner posts the lid screws into');
    out.push('      for (sx = [0, 1], sy = [0, 1])');
    out.push('        translate([sx == 0 ? 5 : outer_w - 5, sy == 0 ? 5 : outer_d - 5, wall])');
    out.push('          cylinder(h = inner_h, r = 4);');
    out.push('    }');
    out.push('    // the cavity');
    out.push('    translate([wall, wall, wall]) cube([inner_w, inner_d, inner_h + 1]);');
    out.push('    // lid screw pilot holes');
    out.push('    for (sx = [0, 1], sy = [0, 1])');
    out.push('      translate([sx == 0 ? 5 : outer_w - 5, sy == 0 ? 5 : outer_d - 5, wall - 1])');
    out.push('        cylinder(h = inner_h + 2, d = 2.6);');
    L.byMount.front.forEach(function (part) {
      out.push('    // ' + part.name + ' — front-wall holes');
      if (part.holeGap) {
        out.push('    translate([' + part.key + '_cx - ' + part.key + '_hole_gap / 2, wall + 1, wall + ' + part.key + '_h / 2]) rotate([90, 0, 0]) cylinder(h = wall + 2, d = ' + part.key + '_hole_d);');
        out.push('    translate([' + part.key + '_cx + ' + part.key + '_hole_gap / 2, wall + 1, wall + ' + part.key + '_h / 2]) rotate([90, 0, 0]) cylinder(h = wall + 2, d = ' + part.key + '_hole_d);');
      } else if (part.holeD) {
        out.push('    translate([' + part.key + '_cx, wall + 1, wall + ' + part.key + '_h / 2]) rotate([90, 0, 0]) cylinder(h = wall + 2, d = ' + part.key + '_hole_d);');
      }
    });
    L.byMount.slot.forEach(function (part) {
      out.push('    // ' + part.name + ' — exit slot in the front wall');
      out.push('    translate([wall + inner_w / 2 - ' + part.key + '_slot_w / 2, -1, wall]) cube([' + part.key + '_slot_w, wall + 2, ' + part.key + '_slot_h]);');
    });
    out.push('  }');
    out.push('}');
    out.push('');

    /* lid */
    out.push('module lid() {');
    out.push('  difference() {');
    out.push('    cube([outer_w, outer_d, lid_t]);');
    out.push('    // lid screw holes (M3 clearance)');
    out.push('    for (sx = [0, 1], sy = [0, 1])');
    out.push('      translate([sx == 0 ? 5 : outer_w - 5, sy == 0 ? 5 : outer_d - 5, -1])');
    out.push('        cylinder(h = lid_t + 2, d = 3.2);');
    L.byMount.lid.forEach(function (part) {
      out.push('    // ' + part.name);
      if (part.holes && part.holeGap) {
        out.push('    for (i = [0 : ' + part.key + '_holes - 1])');
        out.push('      translate([' + part.key + '_cx - (' + part.key + '_holes - 1) * ' + part.key + '_hole_gap / 2 + i * ' + part.key + '_hole_gap, outer_d / 2, -1])');
        out.push('        cylinder(h = lid_t + 2, d = ' + part.key + '_hole_d);');
      } else if (part.ventD) {
        out.push('    for (i = [-1 : 1])');
        out.push('      translate([' + part.key + '_cx + i * 8, outer_d / 2, lid_t / 2])');
        out.push('        cube([4, ' + part.key + '_vent_d, lid_t + 2], center = true);');
      } else if (part.holeD) {
        out.push('    translate([' + part.key + '_cx, outer_d / 2, -1]) cylinder(h = lid_t + 2, d = ' + part.key + '_hole_d);');
      }
    });
    out.push('  }');
    out.push('}');
    out.push('');

    /* primary-sensor mounts, where a printed mount makes sense */
    L.parts.forEach(function (part) {
      if (part.key === 'pir') {
        out.push('// Retaining ring: glue it over the PIR dome hole on the lid.');
        out.push('module pir_mount() {');
        out.push('  difference() {');
        out.push('    cylinder(h = 3, d = pir_hole_d + 12);');
        out.push('    translate([0, 0, -1]) cylinder(h = 5, d = pir_hole_d);');
        out.push('  }');
        out.push('}');
        out.push('');
      }
      if (part.key === 'sr04') {
        out.push('// Bezel: frames the HC-SR04 eyes on the front wall; glue or');
        out.push('// screw it over the sensor from inside.');
        out.push('module sr04_bezel() {');
        out.push('  difference() {');
        out.push('    translate([-(sr04_w + 10) / 2, 0, -(sr04_h + 10) / 2]) cube([sr04_w + 10, 3, sr04_h + 10]);');
        out.push('    translate([-sr04_hole_gap / 2, 4, 0]) rotate([90, 0, 0]) cylinder(h = 5, d = sr04_hole_d);');
        out.push('    translate([sr04_hole_gap / 2, 4, 0]) rotate([90, 0, 0]) cylinder(h = 5, d = sr04_hole_d);');
        out.push('  }');
        out.push('}');
        out.push('');
      }
      if (part.key === 'servo') {
        out.push('// Servo bracket: sits on the lid; the SG90 body drops into');
        out.push('// the window and its flange screws hold it.');
        out.push('module servo_bracket() {');
        out.push('  difference() {');
        out.push('    cube([servo_w + 12, servo_d + 12, 4]);');
        out.push('    translate([6, 6, -1]) cube([servo_w, servo_d, 6]);');
        out.push('  }');
        out.push('}');
        out.push('');
      }
      if (part.key === 'ldrpanel') {
        out.push('// LDR panel: mounts on the servo horn. Two GL5528 holes with');
        out.push('// a divider fin between them, so each eye sees its own side.');
        out.push('module ldr_panel() {');
        out.push('  difference() {');
        out.push('    cube([ldrpanel_w, 3, ldrpanel_h]);');
        out.push('    translate([ldrpanel_w / 2 - ldrpanel_hole_gap / 2, 4, ldrpanel_h / 2]) rotate([90, 0, 0]) cylinder(h = 5, d = ldrpanel_hole_d);');
        out.push('    translate([ldrpanel_w / 2 + ldrpanel_hole_gap / 2, 4, ldrpanel_h / 2]) rotate([90, 0, 0]) cylinder(h = 5, d = ldrpanel_hole_d);');
        out.push('  }');
        out.push('  translate([ldrpanel_w / 2 - 1, 0, 0]) cube([2, 9, ldrpanel_h]);');
        out.push('}');
        out.push('');
      }
    });

    /* assembly */
    out.push('// ---------- assembly (printable parts laid out) ----------');
    out.push('shell();');
    out.push('translate([0, 0, wall + inner_h + explode]) lid();');
    L.parts.forEach(function (part) {
      if (part.key === 'pir') out.push('translate([pir_cx, outer_d / 2, wall + inner_h + explode + lid_t + 8]) pir_mount();');
      if (part.key === 'sr04') out.push('translate([sr04_cx, -14, wall + sr04_h / 2]) sr04_bezel();');
      if (part.key === 'servo') out.push('translate([outer_w / 2 - (servo_w + 12) / 2, outer_d / 2 - (servo_d + 12) / 2, wall + inner_h + explode + lid_t]) servo_bracket();');
      if (part.key === 'ldrpanel') out.push('translate([0, outer_d + 12, 0]) ldr_panel();');
    });
    out.push('');
    return out.join('\n');
  }

  /* ------------------------------------------------ wiring diagram (.svg)
     A standalone SVG drawn from the project's actual wiring rows: every
     connection the guide lists, with the Arduino pin it lands on. Pins are
     read from the rows themselves, so custom pin choices show up here. */

  var SVG_WIRE_COLORS = ['#FF6B1A', '#2978B5', '#5B8C5A', '#C532AD', '#B8860B', '#18888E', '#7A4FA3', '#B3261E'];

  function buildWiringSvg(project) {
    var esc = window.VFUtil.esc;
    var pinRe = /(D\d{1,2}|A\d|5V|GND)/;
    var wired = [], notes = [];
    project.wiring.forEach(function (w) {
      var pin = null, device = null, m;
      if (/^Arduino /.test(w.to)) { m = w.to.match(pinRe); pin = m ? m[1] : null; device = w.from; }
      else if (/^Arduino /.test(w.from)) { m = w.from.match(pinRe); pin = m ? m[1] : null; device = w.to; }
      if (pin) wired.push({ pin: pin, device: device, note: w.note || '' });
      else notes.push(w.from + ' -> ' + w.to + (w.note ? ' (' + w.note + ')' : ''));
    });

    var W = 920, rowH = 34, top = 108;
    var boxH = Math.max(120, wired.length * rowH + 24);
    var H = top + boxH + notes.length * 20 + 78;
    var boxX = 540, boxW = 300, boxY = top;
    var s = [];
    s.push('<?xml version="1.0" encoding="UTF-8"?>');
    s.push('<svg xmlns="http://www.w3.org/2000/svg" width="' + W + '" height="' + H + '" viewBox="0 0 ' + W + ' ' + H + '" font-family="Inter, Arial, sans-serif">');
    s.push('<rect x="0" y="0" width="' + W + '" height="' + H + '" fill="#FAF6EF"/>');
    s.push('<g transform="translate(24,14) scale(0.4)"><polygon points="50,4 90,27 90,73 50,96 10,73 10,27" fill="none" stroke="#181820" stroke-width="7"/><polygon points="56,14 30,54 47,54 40,86 72,44 54,44" fill="#FF6B1A"/></g>');
    s.push('<text x="72" y="34" font-size="21" font-weight="700" fill="#181820">' + esc(project.name) + ' — wiring diagram</text>');
    s.push('<text x="72" y="56" font-size="13.5" fill="#55555f">' + esc(project.blockName) + ' · every connection from the build guide, with the pins your settings chose</text>');

    s.push('<rect x="' + boxX + '" y="' + boxY + '" width="' + boxW + '" height="' + boxH + '" rx="12" fill="#181820"/>');
    s.push('<text x="' + (boxX + boxW / 2) + '" y="' + (boxY + 26) + '" font-size="15" font-weight="700" fill="#FAF6EF" text-anchor="middle">Arduino Uno R3</text>');

    wired.forEach(function (row, i) {
      var y = top + 44 + i * rowH;
      var color = SVG_WIRE_COLORS[i % SVG_WIRE_COLORS.length];
      var label = row.device.length > 52 ? row.device.slice(0, 49) + '...' : row.device;
      s.push('<text x="24" y="' + (y + 4) + '" font-size="13.5" fill="#181820">' + esc(label) + '</text>');
      if (row.note) s.push('<text x="24" y="' + (y + 18) + '" font-size="10.5" fill="#55555f">' + esc(row.note.length > 62 ? row.note.slice(0, 59) + '...' : row.note) + '</text>');
      s.push('<line x1="430" y1="' + y + '" x2="' + boxX + '" y2="' + y + '" stroke="' + color + '" stroke-width="2.5"/>');
      s.push('<circle cx="430" cy="' + y + '" r="4.5" fill="' + color + '"/>');
      s.push('<circle cx="' + boxX + '" cy="' + y + '" r="4.5" fill="' + color + '"/>');
      s.push('<text x="' + (boxX + 16) + '" y="' + (y + 4) + '" font-size="13.5" font-weight="600" fill="#FAF6EF">' + esc(row.pin) + '</text>');
    });

    var ny = top + boxH + 26;
    notes.forEach(function (n) {
      s.push('<text x="24" y="' + ny + '" font-size="12" fill="#55555f">Also: ' + esc(n.length > 118 ? n.slice(0, 115) + '...' : n) + '</text>');
      ny += 20;
    });

    s.push('<text x="24" y="' + (H - 22) + '" font-size="13" fill="#181820"><tspan font-weight="700">' + SITE_NAME + '</tspan> — ' + TAGLINE + '</text>');
    s.push('<text x="' + (W - 24) + '" y="' + (H - 22) + '" font-size="13" fill="#55555f" text-anchor="end">https://' + SITE_URL + '</text>');
    s.push('</svg>');
    return s.join('\n') + '\n';
  }

  window.VFEngine = {
    SITE_NAME: SITE_NAME,
    SITE_URL: SITE_URL,
    TAGLINE: TAGLINE,
    MAX_PROMPT: MAX_PROMPT,
    DIGITAL_PINS: DIGITAL_PINS,
    ANALOG_PINS: ANALOG_PINS,
    blockById: blockById,
    match: match,
    defaultParams: defaultParams,
    validateParams: validateParams,
    generate: generate,
    buildSketchFile: buildSketchFile,
    buildBomCsv: buildBomCsv,
    buildProjectJson: buildProjectJson,
    buildGuideHtml: buildGuideHtml,
    buildScadFile: buildScadFile,
    buildWiringSvg: buildWiringSvg,
    UPLOAD_STEPS: UPLOAD_STEPS
  };
